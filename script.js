let currentLang = localStorage.getItem('wedding_invite_lang') || 'en';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('wedding_invite_lang', lang);

    const btnEn = document.getElementById('btnEn');
    const btnZh = document.getElementById('btnZh');
    
    if (btnEn && btnZh) {
        btnEn.classList.remove('active');
        btnZh.classList.remove('active');
        if (lang === 'en') {
            btnEn.classList.add('active');
            document.documentElement.lang = 'en';
        } else {
            btnZh.classList.add('active');
            document.documentElement.lang = 'zh-TW';
        }
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (translations[lang][key]) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (translations[lang][key]) {
            el.setAttribute('data-title', translations[lang][key]);
        }
    });
}

document.addEventListener('DOMContentLoaded', function () {
    // Initialize language
    setLanguage(currentLang);

    // Page section DOM references
    const sections = Array.from(document.querySelectorAll('.page-section'));
    const navDots = document.querySelectorAll('.nav-dots .dot');

    // 4. Intersection Observer for Entrance Animations and Navigation Dots
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.30
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            entry.target.classList.toggle('in-view', entry.isIntersecting);
            if (entry.isIntersecting) {
                const currentId = entry.target.getAttribute('id');
                navDots.forEach(dot => {
                    if (dot.getAttribute('href') === `#${currentId}`) {
                        dot.classList.add('active');
                    } else {
                        dot.classList.remove('active');
                    }
                });
            }
        });
    }, observerOptions);

    sections.forEach(section => observer.observe(section));

    // 5. RSVP Form Submission Handler
    const rsvpForm = document.getElementById('rsvpForm');
    const rsvpAlert = document.getElementById('rsvpAlert');

    if (rsvpForm) {
        rsvpForm.addEventListener('submit', function (e) {
            e.preventDefault();

            const fullName = document.getElementById('fullName').value.trim();
            const email = document.getElementById('email').value.trim();

            if (!fullName || !email) {
                const errText = translations[currentLang].p7_validation_err;
                alert(errText);
                return;
            }

            if (rsvpAlert) {
                rsvpAlert.classList.remove('d-none');
                rsvpAlert.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
            }

            rsvpForm.reset();
        });
    }

    // 6. Map button listener
    const mapBtn = document.getElementById('mapBtn');
    if (mapBtn) {
        mapBtn.addEventListener('click', function (e) {
            e.preventDefault();
            const mapAlert = translations[currentLang].p4_map_alert;
            alert(mapAlert);
        });
    }

    // 7. Vanilla JS Accordion Toggler for FAQ (replaces jQuery & Bootstrap JS dependencies)
    const faqButtons = document.querySelectorAll('#weddingFaq [data-toggle="collapse"]');
    faqButtons.forEach(btn => {
        btn.addEventListener('click', function (e) {
            e.preventDefault();
            const targetId = this.getAttribute('data-target');
            const targetEl = document.querySelector(targetId);
            if (!targetEl) return;

            const isShown = targetEl.classList.contains('show');

            // Close all collapses in FAQ accordion
            document.querySelectorAll('#weddingFaq .collapse').forEach(c => c.classList.remove('show'));
            document.querySelectorAll('#weddingFaq [data-toggle="collapse"]').forEach(b => {
                b.classList.add('collapsed');
                b.setAttribute('aria-expanded', 'false');
            });

            // Toggle selected item
            if (!isShown) {
                targetEl.classList.add('show');
                this.classList.remove('collapsed');
                this.setAttribute('aria-expanded', 'true');
            }
        });
    });
});
