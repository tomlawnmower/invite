let currentLang = localStorage.getItem('wedding_invite_lang') || 'zh-tw';

function setLanguage(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem('wedding_invite_lang', lang);

    const btnEn = document.getElementById('btnEn');
    const btnZh = document.getElementById('btnZh');
    
    if (btnEn && btnZh) {
        btnEn.classList.remove('active');
        btnZh.classList.remove('active');
        if (lang === 'en') {
            btnEn.classList.add('active');
            document.documentElement.lang = 'en';
        } else {
            btnZh.classList.add('active');
            document.documentElement.lang = 'zh-TW';
        }
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (translations[lang][key]) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (translations[lang][key]) {
            el.setAttribute('data-title', translations[lang][key]);
        }
    });
}

document.addEventListener('DOMContentLoaded', function () {
    // Initialize language
    setLanguage(currentLang);

    // Page section DOM references
    const sections = Array.from(document.querySelectorAll('.page-section'));
    const navDots = document.querySelectorAll('.nav-dots .dot');

    // 4. Intersection Observer for Entrance Animations and Navigation Dots
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.30
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            entry.target.classList.toggle('in-view', entry.isIntersecting);
            if (entry.isIntersecting) {
                const currentId = entry.target.getAttribute('id');
                navDots.forEach(dot => {
                    if (dot.getAttribute('href') === `#${currentId}`) {
                        dot.classList.add('active');
                    } else {
                        dot.classList.remove('active');
                    }
                });
            }
        });
    }, observerOptions);

    sections.forEach(section => observer.observe(section));

    // 5. RSVP Form Submission & Attendance Handler
    const rsvpForm = document.getElementById('rsvpForm');
    const rsvpAlert = document.getElementById('rsvpAlert');
    const attendanceSelect = document.getElementById('attendance');
    let previousGuestCount = '1';

    function updateAttendanceState() {
        if (!attendanceSelect) return;
        const isDeclining = (attendanceSelect.value === 'no');
        const disabledFieldIds = ['guestCount', 'dietary'];

        disabledFieldIds.forEach(id => {
            const field = document.getElementById(id);
            if (field) {
                field.disabled = isDeclining;
            }
        });

        const guestCountSelect = document.getElementById('guestCount');
        if (guestCountSelect) {
            if (isDeclining) {
                if (guestCountSelect.value !== '0') {
                    previousGuestCount = guestCountSelect.value;
                }
                guestCountSelect.value = '0';
            } else {
                if (guestCountSelect.value === '0') {
                    guestCountSelect.value = previousGuestCount || '1';
                }
            }
        }
    }

    if (attendanceSelect) {
        attendanceSelect.addEventListener('change', updateAttendanceState);
        updateAttendanceState();
    }

    // Google Form Integration Constants
    const GOOGLE_FORM_URL = 'https://docs.google.com/forms/d/e/1FAIpQLScPbD6UodpQwa3F_IfahJ75zM4M-PefpCZgp-HKwJBxUNEsgw/formResponse';
    const GOOGLE_ENTRY_IDS = {
        fullName: 'entry.1498135098',
        attendance: 'entry.877086558',
        guestCount: 'entry.1424661284',
        dietary: 'entry.2606285',
        notes: 'entry.2069830961'
    };

    if (rsvpForm) {
        rsvpForm.addEventListener('submit', function (e) {
            e.preventDefault();
            console.log('[RSVP] Submit button clicked');

            const fullNameInput = document.getElementById('fullName');
            const fullName = fullNameInput ? fullNameInput.value.trim() : '';

            if (!fullName) {
                console.warn('[RSVP] Full Name is empty! Validation failed.');
                const errText = translations[currentLang].p7_validation_err;
                alert(errText);
                return;
            }

            const submitBtn = rsvpForm.querySelector('button[type="submit"]');
            if (submitBtn) submitBtn.disabled = true;

            const guestCountSelect = document.getElementById('guestCount');
            const dietarySelect = document.getElementById('dietary');
            const notesInput = document.getElementById('notes');

            // Map website values to exact strings expected by Google Forms
            let attendanceVal = "Yes,  I'll be there";
            if (attendanceSelect && attendanceSelect.value === 'no') {
                attendanceVal = "Sorry, can't make it";
            }

            const guestCountVal = (attendanceSelect && attendanceSelect.value === 'no') 
                ? '0' 
                : (guestCountSelect ? guestCountSelect.value : '1');

            let dietaryVal = '';
            if (attendanceSelect && attendanceSelect.value !== 'no' && dietarySelect) {
                const dietMap = {
                    'standard': 'Standard Menu',
                    'vegetarian': 'Vegetarian',
                    'vegan': 'Vegan',
                    'gluten-free': 'Gluten free'
                };
                dietaryVal = dietMap[dietarySelect.value] || 'Standard Menu';
            }

            const notesVal = notesInput ? notesInput.value.trim() : '';

            const formData = new URLSearchParams();
            formData.append(GOOGLE_ENTRY_IDS.fullName, fullName);
            formData.append(GOOGLE_ENTRY_IDS.attendance, attendanceVal);
            if (guestCountVal && guestCountVal !== '0') {
                formData.append(GOOGLE_ENTRY_IDS.guestCount, guestCountVal);
            }
            if (dietaryVal) {
                formData.append(GOOGLE_ENTRY_IDS.dietary, dietaryVal);
            }
            if (notesVal) {
                formData.append(GOOGLE_ENTRY_IDS.notes, notesVal);
            }

            console.log('[RSVP] Sending POST request to Google Form...');
            console.log('[RSVP] Endpoint:', GOOGLE_FORM_URL);
            console.log('[RSVP] Payload:', formData.toString());

            fetch(GOOGLE_FORM_URL, {
                method: 'POST',
                mode: 'no-cors',
                body: formData
            }).then(() => {
                console.log('[RSVP] Google Form submission request sent successfully!');
                if (rsvpAlert) {
                    rsvpAlert.classList.remove('d-none');
                    rsvpAlert.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
                }
                rsvpForm.reset();
                previousGuestCount = '1';
                updateAttendanceState();
            }).catch((err) => {
                console.error('[RSVP] Error submitting RSVP:', err);
                if (rsvpAlert) {
                    rsvpAlert.classList.remove('d-none');
                }
            }).finally(() => {
                if (submitBtn) submitBtn.disabled = false;
            });
        });
    }

    // 6. Map Thumbnail Lightbox Modal Handler
    const mapThumbBtn = document.getElementById('mapThumbBtn');
    const mapModal = document.getElementById('mapModal');
    const closeMapModalBtn = document.getElementById('closeMapModalBtn');

    function openMapModal() {
        if (mapModal) {
            mapModal.classList.add('open');
            mapModal.setAttribute('aria-hidden', 'false');
            document.body.style.overflow = 'hidden';
        }
    }

    function closeMapModal() {
        if (mapModal) {
            mapModal.classList.remove('open');
            mapModal.setAttribute('aria-hidden', 'true');
            document.body.style.overflow = '';
        }
    }

    if (mapThumbBtn) {
        mapThumbBtn.addEventListener('click', openMapModal);
        mapThumbBtn.addEventListener('keydown', function (e) {
            if (e.key === 'Enter' || e.key === ' ') {
                e.preventDefault();
                openMapModal();
            }
        });
    }

    if (closeMapModalBtn) {
        closeMapModalBtn.addEventListener('click', closeMapModal);
    }

    if (mapModal) {
        mapModal.addEventListener('click', function (e) {
            if (e.target === mapModal) {
                closeMapModal();
            }
        });
        document.addEventListener('keydown', function (e) {
            if (e.key === 'Escape' && mapModal.classList.contains('open')) {
                closeMapModal();
            }
        });
    }

    // Add to Calendar Dropdown & Links Handler
    const calendarDropdownWrapper = document.getElementById('calendarDropdownWrapper');
    const calendarBtn = document.getElementById('calendarBtn');
    const calGoogle = document.getElementById('calGoogle');
    const calApple = document.getElementById('calApple');
    const calOutlook = document.getElementById('calOutlook');
    const calIcs = document.getElementById('calIcs');

    const calEvent = {
        title: "Pin-Chun & Thomas's Wedding",
        location: "Mandarin Oriental, Taipei (8F: Grand Salon), No. 158 Dunhua North Road, Taipei, 10548",
        details: "Official Wedding Invitation for Pin-Chun & Thomas.\n\nSchedule:\n4:30 PM Ceremony Guest Arrival\n4:45 PM Wedding Ceremony\n5:30 PM Check-in, Gift Reception, Cocktail Hour & Candy Bar\n6:00 PM Reception Begins",
        startUtc: "20261212T083000Z",
        endUtc: "20261212T133000Z",
        startIso: "2026-12-12T08:30:00Z",
        endIso: "2026-12-12T13:30:00Z"
    };

    if (calGoogle) {
        const googleUrl = `https://calendar.google.com/calendar/render?action=TEMPLATE` +
            `&text=${encodeURIComponent(calEvent.title)}` +
            `&dates=${calEvent.startUtc}/${calEvent.endUtc}` +
            `&details=${encodeURIComponent(calEvent.details)}` +
            `&location=${encodeURIComponent(calEvent.location)}`;
        calGoogle.href = googleUrl;
    }

    if (calOutlook) {
        const outlookUrl = `https://outlook.live.com/calendar/0/deeplink/compose?path=/calendar/action/compose&rru=addevent` +
            `&subject=${encodeURIComponent(calEvent.title)}` +
            `&startdt=${calEvent.startIso}` +
            `&enddt=${calEvent.endIso}` +
            `&location=${encodeURIComponent(calEvent.location)}` +
            `&body=${encodeURIComponent(calEvent.details)}`;
        calOutlook.href = outlookUrl;
    }

    function generateIcsBlobUrl() {
        const icsContent = [
            'BEGIN:VCALENDAR',
            'VERSION:2.0',
            'PRODID:-//Pin-Chun & Thomas Wedding//EN',
            'CALSCALE:GREGORIAN',
            'METHOD:PUBLISH',
            'BEGIN:VEVENT',
            'UID:wedding-pin-chun-thomas-20261212@invitation',
            `DTSTAMP:${new Date().toISOString().replace(/[-:]/g, '').split('.')[0]}Z`,
            `DTSTART:${calEvent.startUtc}`,
            `DTEND:${calEvent.endUtc}`,
            `SUMMARY:${calEvent.title}`,
            `DESCRIPTION:${calEvent.details.replace(/\n/g, '\\n')}`,
            `LOCATION:${calEvent.location}`,
            'STATUS:CONFIRMED',
            'END:VEVENT',
            'END:VCALENDAR'
        ].join('\r\n');

        const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
        return URL.createObjectURL(blob);
    }

    function downloadIcsFile(e) {
        if (e) e.preventDefault();
        const url = generateIcsBlobUrl();
        const a = document.createElement('a');
        a.href = url;
        a.download = 'pin-chun-and-thomas-wedding.ics';
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        setTimeout(() => URL.revokeObjectURL(url), 200);
    }

    if (calApple) {
        calApple.addEventListener('click', downloadIcsFile);
    }
    if (calIcs) {
        calIcs.addEventListener('click', downloadIcsFile);
    }

    if (calendarBtn && calendarDropdownWrapper) {
        calendarBtn.addEventListener('click', function (e) {
            e.stopPropagation();
            const isOpen = calendarDropdownWrapper.classList.toggle('open');
            calendarBtn.setAttribute('aria-expanded', isOpen);
        });

        document.addEventListener('click', function (e) {
            if (!calendarDropdownWrapper.contains(e.target)) {
                calendarDropdownWrapper.classList.remove('open');
                calendarBtn.setAttribute('aria-expanded', 'false');
            }
        });

        document.addEventListener('keydown', function (e) {
            if (e.key === 'Escape' && calendarDropdownWrapper.classList.contains('open')) {
                calendarDropdownWrapper.classList.remove('open');
                calendarBtn.setAttribute('aria-expanded', 'false');
            }
        });
    }

    // 7. Vanilla JS Accordion Toggler for FAQ (replaces jQuery & Bootstrap JS dependencies)
    const faqButtons = document.querySelectorAll('#weddingFaq [data-toggle="collapse"]');
    faqButtons.forEach(btn => {
        btn.addEventListener('click', function (e) {
            e.preventDefault();
            const targetId = this.getAttribute('data-target');
            const targetEl = document.querySelector(targetId);
            if (!targetEl) return;

            const isShown = targetEl.classList.contains('show');

            // Close all collapses in FAQ accordion
            document.querySelectorAll('#weddingFaq .collapse').forEach(c => c.classList.remove('show'));
            document.querySelectorAll('#weddingFaq [data-toggle="collapse"]').forEach(b => {
                b.classList.add('collapsed');
                b.setAttribute('aria-expanded', 'false');
            });

            // Toggle selected item
            if (!isShown) {
                targetEl.classList.add('show');
                this.classList.remove('collapsed');
                this.setAttribute('aria-expanded', 'true');
            }
        });
    });

    // 8. Floating Site Menu Toggle & Click Outside Handler
    const menuWrapper = document.getElementById('siteMenuWrapper');
    const menuToggleBtn = document.getElementById('menuToggleBtn');
    const siteMenuLinks = document.querySelectorAll('.site-menu-dropdown .menu-link');

    if (menuToggleBtn && menuWrapper) {
        menuToggleBtn.addEventListener('click', function (e) {
            e.stopPropagation();
            const isOpen = menuWrapper.classList.toggle('open');
            menuToggleBtn.setAttribute('aria-expanded', isOpen);
            const icon = menuToggleBtn.querySelector('.menu-icon');
            if (icon) {
                if (isOpen) {
                    icon.classList.remove('fa-bars');
                    icon.classList.add('fa-xmark');
                } else {
                    icon.classList.remove('fa-xmark');
                    icon.classList.add('fa-bars');
                }
            }
        });

        siteMenuLinks.forEach(link => {
            link.addEventListener('click', function () {
                menuWrapper.classList.remove('open');
                menuToggleBtn.setAttribute('aria-expanded', 'false');
                const icon = menuToggleBtn.querySelector('.menu-icon');
                if (icon) {
                    icon.classList.remove('fa-xmark');
                    icon.classList.add('fa-bars');
                }
            });
        });

        document.addEventListener('click', function (e) {
            if (!menuWrapper.contains(e.target)) {
                menuWrapper.classList.remove('open');
                menuToggleBtn.setAttribute('aria-expanded', 'false');
                const icon = menuToggleBtn.querySelector('.menu-icon');
                if (icon) {
                    icon.classList.remove('fa-xmark');
                    icon.classList.add('fa-bars');
                }
            }
        });
    }
});
